package.path = "src/?.lua;src/?/init.lua;" .. package.path
local z = require "ir.zosung"
-- Literal LZ block: 03 84 03 A8 61; base64 = A4QDqGE=
assert(z.encode_timings({900, 25000}) == "A4QDqGE=")
assert(z.checksum("ABC") == 198)
local s = z.new_session(string.rep("A", 101), 42)
local cmd, initial = s:start()
assert(cmd == 0 and initial.length == 101 and initial.unk2 == 0xE004)
assert(not pcall(function() s:acknowledge(42) end))
local part_cmd, part = s:requested_part(42, 0)
assert(part_cmd == 3 and part.position == 0 and #part.msgpart == 50)
local retry_cmd, retry = s:requested_part(42, 0)
assert(retry_cmd == 3 and retry.msgpart == part.msgpart and retry.msgpartcrc == part.msgpartcrc)
assert(not pcall(function() s:requested_part(42, 25) end))
part_cmd, part = s:requested_part(42, 50)
assert(part_cmd == 3 and part.position == 50 and #part.msgpart == 50)
assert(part.msgpartcrc == (50 * 65) % 256)
part_cmd, part = s:requested_part(42, 100)
assert(part_cmd == 3 and part.position == 100 and #part.msgpart == 1)
assert(not pcall(function() s:requested_part(43, 0) end))
assert(not pcall(function() s:requested_part(42, 101) end))
local done_cmd = s:acknowledge(42)
assert(done_cmd == 5 and s.complete)
assert(not pcall(function() s:requested_part(42, 0) end))
local incomplete = z.new_session("ABC", 43)
incomplete:start()
assert(not pcall(function() incomplete:acknowledge(43) end))
assert(not pcall(function() z.encode_timings({70000, 500}) end))
local capture = z.new_capture(10)
local start = capture:begin(7, 5, { cmd = 1, unk2 = 0xE004 })
assert(start[1].cmd == 1 and start[2].payload.maxlen == 0x38)
assert(not pcall(function() capture:part(7, 0, "ab", 0) end))
local next_cmd, request = capture:part(7, 0, "ab", z.checksum("ab"))
assert(next_cmd == 2 and request.position == 2)
assert(not pcall(function() capture:part(7, 0, "cd", z.checksum("cd")) end))
local end_cmd = capture:part(7, 2, "cde", z.checksum("cde"))
assert(end_cmd == 4 and capture:finish(7) == "YWJjZGU=")
assert(not pcall(function() z.new_capture(4):begin(1, 5) end))
print("Zosung send-side tests passed")
